# ---------------------------------------------------------------- 1. questions
def qblock(course, d):
    rows = sorted(d['questions'], key=lambda q: (TIERS.index(q['tier']), q['scope'], q['module_key'] or '', q['ord']))
    w('-- ----------------------------------------------------------------------------')
    w(f'-- 1. {course}: {len(rows)} question rows.')
    w('-- ----------------------------------------------------------------------------')
    w('do $$')
    w('declare')
    w('  r         record;')
    w('  v_state   text;')
    w('  v_count   integer;')
    w('  v_updated integer := 0;')
    w('  v_done    integer := 0;')
    w('begin')
    w('  for r in')
    w('    select * from (values')
    vals = []
    for q in rows:
        o, n = q['old'], q['new']
        vals.append('      (' + ', '.join([lit(q['tier']), lit(q['scope']), lit(q['module_key']) + '::text', str(q['ord']),
                    lit(o['prompt']), jlit(o['options']), str(o['answer_index']), lit(o['explanation']) + '::text',
                    lit(n['prompt']), jlit(n['options']), str(n['answer_index']), lit(n['explanation']) + '::text']) + ')')
    w(',\n'.join(vals))
    w('    ) as t(tier, scope, module_key, ord, old_prompt, old_options, old_answer, old_expl, new_prompt, new_options, new_answer, new_expl)')
    w('  loop')
    w("    select case")
    w("             when q.prompt = r.old_prompt and q.options = r.old_options and q.answer_index = r.old_answer and q.explanation is not distinct from r.old_expl then 'old'")
    w("             when q.prompt = r.new_prompt and q.options = r.new_options and q.answer_index = r.new_answer and q.explanation is not distinct from r.new_expl then 'new'")
    w("             else 'other' end")
    w('      into v_state')
    w('      from public.academy_quiz_questions q')
    w(f"     where q.app_slug = '{course}' and q.active and q.tier = r.tier and q.scope = r.scope")
    w('       and q.module_key is not distinct from r.module_key and q.ord = r.ord;')
    w('    get diagnostics v_count = row_count;')
    w('    if v_count <> 1 then')
    w(f"      raise exception 'ec7 pia recut refused: {course}/%/%/%/ord % matched % active rows, expected 1', r.tier, r.scope, coalesce(r.module_key, 'final'), r.ord, v_count;")
    w('    end if;')
    w("    if v_state = 'other' then")
    w(f"      raise exception 'ec7 pia recut refused: {course}/%/%/%/ord % carries neither its published text nor the recut text', r.tier, r.scope, coalesce(r.module_key, 'final'), r.ord;")
    w('    end if;')
    w("    if v_state = 'old' then")
    w('      update public.academy_quiz_questions q')
    w('         set prompt = r.new_prompt, options = r.new_options, answer_index = r.new_answer, explanation = r.new_expl')
    w(f"       where q.app_slug = '{course}' and q.active and q.tier = r.tier and q.scope = r.scope")
    w('         and q.module_key is not distinct from r.module_key and q.ord = r.ord;')
    w('      get diagnostics v_count = row_count;')
    w('      if v_count <> 1 then')
    w(f"        raise exception 'ec7 pia recut refused: {course}/%/%/%/ord % update touched % rows', r.tier, r.scope, coalesce(r.module_key, 'final'), r.ord, v_count;")
    w('      end if;')
    w('      v_updated := v_updated + 1;')
    w('    else')
    w('      v_done := v_done + 1;')
    w('    end if;')
    w('  end loop;')
    w('')
    w("  for r in select t as tier from unnest(array['beginner', 'intermediate', 'advanced']) t loop")
    w(f"    select count(*) into v_count from public.academy_quiz_questions where app_slug = '{course}' and active and tier = r.tier;")
    w('    if v_count <> 132 then')
    w(f"      raise exception 'ec7 pia recut refused: {course}/% holds % active questions, expected 132', r.tier, v_count;")
    w('    end if;')
    w('  end loop;')
    w(f"  select count(*) into v_count from public.academy_quiz_questions where app_slug = '{course}' and active;")
    w('  if v_count <> 396 then')
    w(f"    raise exception 'ec7 pia recut refused: {course} holds % active questions, expected 396', v_count;")
    w('  end if;')
    w(f"  raise notice 'ec7 pia recut: {course} questions, % updated, % already recut, of {len(rows)}', v_updated, v_done;")
    w('end $$;')
    w('')

qblock('cashflow', CF)
qblock('fiscal', FI)

# ---------------------------------------------------------------- 2. capstones
def capblock(course, tier, old, new, label):
    w('-- ----------------------------------------------------------------------------')
    w(f'-- 2. {course} {tier} capstone: {label}.')
    w('-- ----------------------------------------------------------------------------')
    w('do $$')
    w('declare')
    w('  v_state text;')
    w('  v_count integer;')
    w('begin')
    w('  select case')
    for st, v in (('old', old), ('new', new)):
        w(f"           when c.title = {lit(v['title'])}")
        w(f"            and c.dataset = {lit(v['dataset'])}")
        w(f"            and c.cert_tier = {lit(v['cert_tier'])}")
        w(f"            and c.prompt = {lit(v['prompt'])}")
        w(f"            and {canon_sql('c.fields')} = {canon_sql(jlit(v['fields']))} then '{st}'")
    w("           else 'other' end")
    w('    into v_state')
    w(f"    from public.academy_capstones c where c.app_slug = '{course}' and c.tier = '{tier}' and c.active;")
    w('  get diagnostics v_count = row_count;')
    w('  if v_count <> 1 then')
    w(f"    raise exception 'ec7 pia recut refused: {course}/{tier} has % active capstones, expected 1', v_count;")
    w('  end if;')
    w("  if v_state = 'other' then")
    w(f"    raise exception 'ec7 pia recut refused: the {course}/{tier} capstone carries neither its published title, dataset, prompt and fields nor the recut ones';")
    w('  end if;')
    w("  if v_state = 'old' then")
    w('    update public.academy_capstones')
    w(f"       set dataset = {lit(new['dataset'])},")
    w(f"           prompt = {lit(new['prompt'])},")
    w(f"           fields = {jlit(new['fields'])}")
    w(f"     where app_slug = '{course}' and tier = '{tier}' and active;")
    w('    get diagnostics v_count = row_count;')
    w('    if v_count <> 1 then')
    w(f"      raise exception 'ec7 pia recut refused: the {course}/{tier} capstone update touched % rows', v_count;")
    w('    end if;')
    w('  end if;')
    w(f"  select jsonb_array_length(fields) into v_count from public.academy_capstones where app_slug = '{course}' and tier = '{tier}' and active;")
    w('  if v_count <> 6 then')
    w(f"    raise exception 'ec7 pia recut refused: the {course}/{tier} capstone holds % fields, expected 6', v_count;")
    w('  end if;')
    w(f"  raise notice 'ec7 pia recut: {course}/{tier} capstone %', case when v_state = 'old' then 'recut' else 'already recut' end;")
    w('end $$;')
    w('')

capblock('cashflow', 'intermediate', cf_caps['intermediate']['old'], cf_caps['intermediate']['new'], 'prompt only (copy rule), fields unchanged')
capblock('cashflow', 'advanced', cf_caps['advanced']['old'], cf_caps['advanced']['new'], 'dataset, prompt and six graded fields')

# fiscal advanced: prompt only; title, dataset, cert tier and fields asserted unchanged.
w('-- ----------------------------------------------------------------------------')
w('-- 2. fiscal advanced capstone: prompt only (title, dataset and fields unchanged).')
w('-- ----------------------------------------------------------------------------')
w('do $$')
w('declare')
w('  v_prompt text;')
w('  v_before text;')
w('  v_after  text;')
w('  v_count  integer;')
w('begin')
HEAD = "md5(c.title) || ':' || md5(c.dataset) || ':' || c.cert_tier || ':' || " + canon_sql('c.fields')
w(f"  select c.prompt, {HEAD} into v_prompt, v_before from public.academy_capstones c where c.app_slug = 'fiscal' and c.tier = 'advanced' and c.active;")
w('  get diagnostics v_count = row_count;')
w('  if v_count <> 1 then')
w("    raise exception 'ec7 pia recut refused: fiscal/advanced has % active capstones, expected 1', v_count;")
w('  end if;')
w(f"  if v_prompt is distinct from {lit(fpc[0]['old'])} and v_prompt is distinct from {lit(fpc[0]['new'])} then")
w("    raise exception 'ec7 pia recut refused: the fiscal/advanced prompt is neither its published text nor the recut text';")
w('  end if;')
w(f"  if v_prompt = {lit(fpc[0]['old'])} then")
w(f"    update public.academy_capstones set prompt = {lit(fpc[0]['new'])} where app_slug = 'fiscal' and tier = 'advanced' and active;")
w('    get diagnostics v_count = row_count;')
w('    if v_count <> 1 then')
w("      raise exception 'ec7 pia recut refused: the fiscal/advanced prompt update touched % rows', v_count;")
w('    end if;')
w("    raise notice 'ec7 pia recut: fiscal/advanced capstone prompt recut';")
w('  else')
w("    raise notice 'ec7 pia recut: fiscal/advanced capstone prompt already recut';")
w('  end if;')
w(f"  select {HEAD} into v_after from public.academy_capstones c where c.app_slug = 'fiscal' and c.tier = 'advanced' and c.active;")
w('  if v_after is distinct from v_before then')
w("    raise exception 'ec7 pia recut refused: the fiscal/advanced title, dataset, cert tier or fields moved';")
w('  end if;')
w('end $$;')
w('')

# fiscal tolerance
w('-- ----------------------------------------------------------------------------')
w(f"-- 3. fiscal {g['tier']} capstone: {g['key']} tolerance {g['old_tol']!r} -> {g['new_tol']!r}.")
w('--    ' + g['why'].replace('\n', ' '))
w('-- ----------------------------------------------------------------------------')
w('do $$')
w('declare')
w('  v_tol      float8;')
w('  v_expected float8;')
w('  v_n        integer;')
w('  v_count    integer;')
w('begin')
w("  select count(*), max((f->>'tol')::float8), max((f->>'expected')::float8) into v_n, v_tol, v_expected")
w('    from public.academy_capstones c, lateral jsonb_array_elements(c.fields) f')
w(f"   where c.app_slug = 'fiscal' and c.tier = '{g['tier']}' and c.active and f->>'key' = {lit(g['key'])};")
w('  if v_n <> 1 then')
w(f"    raise exception 'ec7 pia recut refused: fiscal/{g['tier']} has % fields keyed {g['key']}, expected 1', v_n;")
w('  end if;')
w(f"  if v_expected is distinct from {g['expected']!r}::float8 then")
w(f"    raise exception 'ec7 pia recut refused: fiscal/{g['tier']}.{g['key']} expects %, not the value this file was generated against', v_expected;")
w('  end if;')
w(f"  if v_tol not in ({g['old_tol']!r}::float8, {g['new_tol']!r}::float8) then")
w(f"    raise exception 'ec7 pia recut refused: fiscal/{g['tier']}.{g['key']} carries tolerance %, neither the published nor the recut one', v_tol;")
w('  end if;')
w(f"  if v_tol = {g['old_tol']!r}::float8 then")
w('    update public.academy_capstones c')
w(f"       set fields = (select jsonb_agg(case when e.f->>'key' = {lit(g['key'])} then jsonb_set(e.f, '{{tol}}', to_jsonb({g['new_tol']!r}::float8)) else e.f end order by e.n)")
w('                       from jsonb_array_elements(c.fields) with ordinality as e(f, n))')
w(f"     where c.app_slug = 'fiscal' and c.tier = '{g['tier']}' and c.active;")
w('    get diagnostics v_count = row_count;')
w('    if v_count <> 1 then')
w(f"      raise exception 'ec7 pia recut refused: fiscal/{g['tier']} tolerance update touched % rows', v_count;")
w('    end if;')
w('  end if;')
w("  select count(*), max((f->>'tol')::float8) into v_n, v_tol")
w('    from public.academy_capstones c, lateral jsonb_array_elements(c.fields) f')
w(f"   where c.app_slug = 'fiscal' and c.tier = '{g['tier']}' and c.active and f->>'key' = {lit(g['key'])};")
w(f"  if v_n <> 1 or v_tol <> {g['new_tol']!r}::float8 then")
w(f"    raise exception 'ec7 pia recut refused: fiscal/{g['tier']}.{g['key']} reads back tolerance %', v_tol;")
w('  end if;')
w("  raise notice 'ec7 pia recut: fiscal tolerance in place';")
w('end $$;')
w('')

# ---------------------------------------------------------------- 4. closing assertions
w('-- ----------------------------------------------------------------------------')
w('-- 4. Closing assertions: 3 capstones of 6 fields per course, 18 fields each,')
w('--    and the attempts and certifications untouched.')
w('-- ----------------------------------------------------------------------------')
w('do $$')
w('declare')
w('  v_count integer;')
w('  v_c     text;')
w('begin')
w("  foreach v_c in array array['cashflow', 'fiscal'] loop")
w('    select count(*) into v_count from public.academy_capstones where app_slug = v_c and active;')
w('    if v_count <> 3 then')
w("      raise exception 'ec7 pia recut refused: % has % active capstones, expected 3', v_c, v_count;")
w('    end if;')
w('    select count(*) into v_count from public.academy_capstones k, lateral jsonb_array_elements(k.fields) f where k.app_slug = v_c and k.active;')
w('    if v_count <> 18 then')
w("      raise exception 'ec7 pia recut refused: % capstones carry % graded fields, expected 18', v_c, v_count;")
w('    end if;')
w('  end loop;')
w(f"  if current_setting('ec7.snapshot', true) is distinct from {SNAP} then")
w("    raise exception 'ec7 pia recut refused: a stored capstone attempt or certification of cashflow or fiscal changed';")
w('  end if;')
w("  raise notice 'ec7 pia recut: done; attempts and certifications untouched';")
w('end $$;')

sql = '\n'.join(L) + '\n'
if '--check' in sys.argv:
    cur = open(OUT).read() if os.path.exists(OUT) else ''
    if cur != sql:
        print('DIFFERS: migrations/20261108_ec7_pia_recut_cashflow_fiscal.sql is not what the generator writes'); sys.exit(1)
    print('generator check: the committed migration is what the manifests produce'); sys.exit(0)
open(OUT, 'w').write(sql)
print(f"wrote {os.path.relpath(OUT, REPO)}: {len(sql)} bytes, sha256 {hashlib.sha256(sql.encode()).hexdigest()}; cashflow {sum(cfc.values())} questions {cfc}, fiscal {sum(fic.values())} questions {fic}")
