w('-- brought onto the PIA 2021 / NTA 2025 compliance repair (petrolord-engines')
w('-- 3778451, engines 3.12.0, default path).')
w('--')
w('-- GENERATED by tools/course-waves/pia-recut/gen_ec7_migration.py from')
w('-- docs/pia-recut/cashflow_edits.json, docs/pia-recut/fiscal_edits.json and')
w('-- tools/course-waves/cashflow/capstones.json. Never hand-edit.')
w('--')
w('-- WHAT MOVES.')
w(f"--   cashflow questions: {sum(cfc.values())} rows (beginner {cfc['beginner']}, intermediate {cfc['intermediate']}, advanced {cfc['advanced']})")
w(f"--   fiscal questions:   {sum(fic.values())} rows (beginner {fic['beginner']}, intermediate {fic['intermediate']}, advanced {fic['advanced']})")
w('--   cashflow Professional capstone: prompt only (owner copy rule); fields unchanged.')
w('--   cashflow Expert capstone: dataset, prompt and the six graded fields. Removed keys:')
w('--     ' + ', '.join(cf_caps['advanced']['graded_keys_removed']))
w('--   added: ' + ', '.join(cf_caps['advanced']['graded_keys_added']))
w('--   kept with a moved expected value: ' + ', '.join(cf_caps['advanced']['graded_keys_kept_value_moved']))
for f in adv_new['fields']:
    w(f"--     {f['key']} = {f['expected']!r} (tol {f['tol']!r} {f['unit']})")
w('--   fiscal Expert capstone: prompt only; fields unchanged.')
g = fgc[0]
w(f"--   fiscal {g['tier']} capstone: {g['key']} tolerance {g['old_tol']!r} -> {g['new_tol']!r} (expected {g['expected']!r} unchanged).")
w('-- No ord, module key, scope or row count moves; each course keeps 396 active')
w('-- questions (132 a tier) and 3 capstones of 6 fields. The served course')
w('-- structure stores module titles and lesson keys only; neither moves, so the')
w('-- two fiscal lesson TITLE changes ship in the site build (manifest.json) and')
w('-- nothing here touches academy_course_structures.')
