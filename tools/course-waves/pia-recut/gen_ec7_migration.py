assert cf_caps['advanced']['new']['fields'] == adv_new['fields'], 'capstones.json advanced fields differ from cashflow_edits.json'
assert cf_caps['advanced']['new']['dataset'] == adv_new['dataset']
assert cf_caps['intermediate']['new']['prompt'] == int_new['prompt']
fpc = FI['capstone_prompt_changes']
assert len(fpc) == 1 and fpc[0]['tier'] == 'advanced' and fpc[0]['field'] == 'prompt'
fgc = FI['graded_field_changes']
assert len(fgc) == 1

