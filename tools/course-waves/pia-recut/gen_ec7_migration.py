import json, os, sys, hashlib

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
OUT = os.path.join(REPO, 'migrations', '20261108_ec7_pia_recut_cashflow_fiscal.sql')
CF = json.load(open(os.path.join(REPO, 'docs/pia-recut/cashflow_edits.json')))
FI = json.load(open(os.path.join(REPO, 'docs/pia-recut/fiscal_edits.json')))
CAPS = json.load(open(os.path.join(REPO, 'tools/course-waves/cashflow/capstones.json')))

def lit(s):
    if s is None:
        return 'null'
    return "'" + str(s).replace("'", "''") + "'"

def jlit(o):
    return lit(json.dumps(o, ensure_ascii=False)) + '::jsonb'

TIERS = ('beginner', 'intermediate', 'advanced')

def canon_sql(expr):
    # One canonical text for a capstone fields array: key|label|unit|expected|tol in order,
    # numbers compared as float8 so the literal's spelling of a number never matters.
    return ("(select string_agg((e.f->>'key') || '|' || coalesce(e.f->>'label', '') || '|' || coalesce(e.f->>'unit', '') || '|' "
            "|| ((e.f->>'expected')::float8)::text || '|' || ((e.f->>'tol')::float8)::text, ',' order by e.n) "
            f"from jsonb_array_elements({expr}) with ordinality as e(f, n))")

L = []
w = L.append

def counts(d):
    c = {t: 0 for t in TIERS}
    for q in d['questions']:
        c[q['tier']] += 1
    return c

cfc, fic = counts(CF), counts(FI)
cf_caps = {c['tier']: c for c in CF['capstones']}
