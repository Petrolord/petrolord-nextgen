#!/usr/bin/env python3
"""Generate migrations/20261014090000_ec1_midyear_recut_cashflow.sql from edits.json.

Never hand-edit the SQL: edit the bank sources, re-emit, rebuild edits.json, and run
    python3 tools/course-waves/cashflow/midyear-recut/gen_migration.py
--check exits 1 if the committed SQL differs from what this would write.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
NAME = '20261014090000_ec1_midyear_recut_cashflow'
OUT = os.path.join(REPO, 'migrations', NAME + '.sql')
ED = json.load(open(os.path.join(HERE, 'edits.json')))


def lit(s):
    return 'null' if s is None else "'" + str(s).replace("'", "''") + "'"


def jlit(o):
    return lit(json.dumps(o, ensure_ascii=False)) + '::jsonb'


def canon(expr):
    # key|label|unit|expected|tol in order, numbers compared as float8 so a literal's spelling never matters
    return ("(select string_agg((e.f->>'key') || '|' || coalesce(e.f->>'label', '') || '|' || coalesce(e.f->>'unit', '') || '|' "
            "|| ((e.f->>'expected')::float8)::text || '|' || ((e.f->>'tol')::float8)::text, ',' order by e.n) "
            f"from jsonb_array_elements({expr}) with ordinality as e(f, n))")


SNAP = ("md5(coalesce((select string_agg(md5(a::text), ',' order by a.id) from public.academy_capstone_attempts a where a.app_slug = 'cashflow'), '') "
        "|| '#' || coalesce((select string_agg(md5(q::text), ',' order by q.id) from public.academy_quiz_attempts q where q.app_slug = 'cashflow'), '') "
        "|| '#' || coalesce((select string_agg(md5(c::text), ',' order by c.id) from public.academy_certifications c where c.app_slug = 'cashflow'), ''))")

qs = ED['questions']
cap = ED['capstones']
assert len(cap) == 1 and cap[0]['tier'] == 'intermediate' and cap[0]['moved_fields'] == ['jv_npv_mid_year_usd'], cap
cap = cap[0]
newmid = [f for f in cap['new']['fields'] if f['key'] == 'jv_npv_mid_year_usd'][0]
oldmid = [f for f in cap['old']['fields'] if f['key'] == 'jv_npv_mid_year_usd'][0]

L = []
w = L.append
w('-- ============================================================================')
w('-- EC1 MID-YEAR RECUT: Cash Flow & NPV (cashflow) brought onto engines 3.12.3')
w('-- (petrolord-engines a6cb037, PR #359; owner decision 2026-10-14: the course')
w('-- must match the Suite). The valuation date is 31 December of the valuation')
w('-- year; mid-year cash arrives half a year before it, so every mid-year exponent')
w('-- is 0.5 SMALLER and mid-year NPV = end-year NPV x sqrt(1 + applied rate).')
w('-- End-year figures do not move.')
w('--')
w('-- GENERATED by tools/course-waves/cashflow/midyear-recut/gen_migration.py from')
w('-- tools/course-waves/cashflow/midyear-recut/edits.json. Never hand-edit.')
w('--')
w('-- WHAT MOVES.')
w(f"--   cashflow questions: {len(qs)} rows (beginner {ED['counts']['beginner']}, intermediate {ED['counts']['intermediate']}, advanced {ED['counts']['advanced']}).")
w('--     No keyed index moves (build_edits.py refuses one); every row keeps its id.')
w('--   cashflow Professional capstone: the prompt\'s mid-year sentence, and one graded field')
w(f"--     jv_npv_mid_year_usd {oldmid['expected']!r} -> {newmid['expected']!r} (tol {newmid['tol']!r} USD).")
w('--   No row count, ord, module key, scope, title, dataset or other field moves.')
w('--   The lessons, panels and lab ship in the NextGen site build.')
w('--')
w('-- ATTEMPTS AND CERTIFICATES. academy_grade_quiz scores a quiz attempt once, at')
w('-- submission, against the answer_index of each question id; academy_submit_capstone')
w('-- scores a capstone attempt once and stores the score. Neither is ever re-run, no')
w('-- trigger exists on academy_quiz_questions or academy_capstones, and this file')
w('-- touches neither attempts table nor academy_certifications. It REPORTS (NOTICE)')
w('-- every cashflow attempt and certification it finds, and asserts that all of them')
w('-- are byte-identical after it. (Read-only production check 2026-10-14: 0 cashflow')
w('-- quiz attempts, 0 capstone attempts, 0 certifications.)')
w('--')
w('-- GUARDS. Each question row is addressed by (app_slug, tier, scope, module_key,')
w('-- ord) and must carry EITHER its served prompt, options, answer_index and')
w('-- explanation exactly (it is updated) OR the recut ones exactly (already applied,')
w('-- left alone). Anything else raises, and in a transaction the whole file rolls')
w('-- back. Every update touches exactly 1 row. The capstone is guarded the same way.')
w('--')
w('-- TRANSACTION. Like every migration in this repository the file carries no')
w('-- begin/commit of its own: apply_ec1_midyear.sh wraps it in one.')
w('-- SAFE TO RE-RUN: a second run finds every row recut and writes nothing.')
w('-- ============================================================================')
w('')
w('-- 0. The attempts and certifications that stand as issued.')
w('do $$')
w('declare')
w('  v_q integer; v_c integer; v_k integer;')
w('begin')
w("  select count(*) into v_q from public.academy_quiz_attempts where app_slug = 'cashflow';")
w("  select count(*) into v_c from public.academy_capstone_attempts where app_slug = 'cashflow';")
w("  select count(*) into v_k from public.academy_certifications where app_slug = 'cashflow';")
w("  raise notice 'ec1 midyear recut: cashflow holds % quiz attempt(s), % capstone attempt(s), % certification(s); all stand as graded and none is re-scored', v_q, v_c, v_k;")
w(f"  perform set_config('ec1mid.snapshot', {SNAP}, false);")
w('end $$;')
w('')
w(f'-- 1. cashflow: {len(qs)} question rows.')
w('do $$')
w('declare')
w('  r         record;')
w('  v_state   text;')
w('  v_count   integer;')
w('  v_updated integer := 0;')
w('  v_done    integer := 0;')
w('begin')
w('  for r in')
w('    select * from (values')
vals = []
for q in qs:
    o, n = q['old'], q['new']
    vals.append('      (' + ', '.join([lit(q['tier']), lit(q['scope']), lit(q['module_key']) + '::text', str(q['ord']),
                                        lit(o['prompt']), jlit(o['options']), str(o['answer_index']), lit(o['explanation']),
                                        lit(n['prompt']), jlit(n['options']), str(n['answer_index']), lit(n['explanation'])]) + ')')
w(',\n'.join(vals))
w('    ) as v(tier, scope, module_key, ord, old_prompt, old_options, old_answer, old_expl, new_prompt, new_options, new_answer, new_expl)')
w('  loop')
w('    select case')
w('             when q.prompt = r.old_prompt and q.options = r.old_options and q.answer_index = r.old_answer and q.explanation is not distinct from r.old_expl then \'old\'')
w('             when q.prompt = r.new_prompt and q.options = r.new_options and q.answer_index = r.new_answer and q.explanation is not distinct from r.new_expl then \'new\'')
w("             else 'other' end")
w('      into v_state')
w('      from public.academy_quiz_questions q')
w("     where q.app_slug = 'cashflow' and q.active and q.tier = r.tier and q.scope = r.scope")
w('       and q.module_key is not distinct from r.module_key and q.ord = r.ord;')
w('    get diagnostics v_count = row_count;')
w('    if v_count <> 1 then')
w("      raise exception 'ec1 midyear recut refused: cashflow/%/%/%/ord % matched % active rows, expected 1', r.tier, r.scope, coalesce(r.module_key, 'final'), r.ord, v_count;")
w('    end if;')
w("    if v_state = 'other' then")
w("      raise exception 'ec1 midyear recut refused: cashflow/%/%/%/ord % carries neither its served text nor the recut text', r.tier, r.scope, coalesce(r.module_key, 'final'), r.ord;")
w('    end if;')
w("    if v_state = 'old' then")
w('      update public.academy_quiz_questions q')
w('         set prompt = r.new_prompt, options = r.new_options, answer_index = r.new_answer, explanation = r.new_expl')
w("       where q.app_slug = 'cashflow' and q.active and q.tier = r.tier and q.scope = r.scope")
w('         and q.module_key is not distinct from r.module_key and q.ord = r.ord;')
w('      get diagnostics v_count = row_count;')
w('      if v_count <> 1 then')
w("        raise exception 'ec1 midyear recut refused: cashflow/%/%/%/ord % update touched % rows', r.tier, r.scope, coalesce(r.module_key, 'final'), r.ord, v_count;")
w('      end if;')
w('      v_updated := v_updated + 1;')
w('    else')
w('      v_done := v_done + 1;')
w('    end if;')
w('  end loop;')
w("  for r in select t as tier from unnest(array['beginner', 'intermediate', 'advanced']) t loop")
w("    select count(*) into v_count from public.academy_quiz_questions where app_slug = 'cashflow' and active and tier = r.tier;")
w('    if v_count <> 132 then')
w("      raise exception 'ec1 midyear recut refused: cashflow/% holds % active questions, expected 132', r.tier, v_count;")
w('    end if;')
w('  end loop;')
w(f"  raise notice 'ec1 midyear recut: cashflow questions, % updated, % already recut, of {len(qs)}', v_updated, v_done;")
w('end $$;')
w('')
w('-- 2. cashflow Professional capstone: the mid-year sentence and jv_npv_mid_year_usd.')
w('do $$')
w('declare')
w('  v_state text;')
w('  v_count integer;')
w('begin')
w('  select case')
w(f"           when c.prompt = {lit(cap['old']['prompt'])}")
w(f"            and {canon('c.fields')} = {canon(jlit(cap['old']['fields']))} then 'old'")
w(f"           when c.prompt = {lit(cap['new']['prompt'])}")
w(f"            and {canon('c.fields')} = {canon(jlit(cap['new']['fields']))} then 'new'")
w("           else 'other' end")
w('    into v_state')
w("    from public.academy_capstones c where c.app_slug = 'cashflow' and c.tier = 'intermediate' and c.active;")
w('  get diagnostics v_count = row_count;')
w('  if v_count <> 1 then')
w("    raise exception 'ec1 midyear recut refused: cashflow/intermediate has % active capstones, expected 1', v_count;")
w('  end if;')
w("  if v_state = 'other' then")
w("    raise exception 'ec1 midyear recut refused: the cashflow/intermediate capstone carries neither its served prompt and fields nor the recut ones';")
w('  end if;')
w("  if v_state = 'old' then")
w('    update public.academy_capstones')
w(f"       set prompt = {lit(cap['new']['prompt'])},")
w(f"           fields = {jlit(cap['new']['fields'])}")
w("     where app_slug = 'cashflow' and tier = 'intermediate' and active;")
w('    get diagnostics v_count = row_count;')
w('    if v_count <> 1 then')
w("      raise exception 'ec1 midyear recut refused: the cashflow/intermediate capstone update touched % rows', v_count;")
w('    end if;')
w('  end if;')
w("  raise notice 'ec1 midyear recut: cashflow/intermediate capstone %', case when v_state = 'old' then 'recut' else 'already recut' end;")
w('end $$;')
w('')
w('-- 3. Closing assertions.')
w('do $$')
w('declare')
w('  v_count integer;')
w('begin')
w("  select count(*) into v_count from public.academy_quiz_questions where app_slug = 'cashflow' and active;")
w('  if v_count <> 396 then')
w("    raise exception 'ec1 midyear recut refused: cashflow holds % active questions, expected 396', v_count;")
w('  end if;')
w("  select count(*) into v_count from public.academy_capstones where app_slug = 'cashflow' and active;")
w('  if v_count <> 3 then')
w("    raise exception 'ec1 midyear recut refused: cashflow has % active capstones, expected 3', v_count;")
w('  end if;')
w("  select count(*) into v_count from public.academy_capstones k, lateral jsonb_array_elements(k.fields) f where k.app_slug = 'cashflow' and k.active;")
w('  if v_count <> 18 then')
w("    raise exception 'ec1 midyear recut refused: cashflow capstones carry % graded fields, expected 18', v_count;")
w('  end if;')
w(f"  if current_setting('ec1mid.snapshot', true) is distinct from {SNAP} then")
w("    raise exception 'ec1 midyear recut refused: a stored cashflow quiz attempt, capstone attempt or certification changed';")
w('  end if;')
w("  raise notice 'ec1 midyear recut: done; attempts and certifications untouched';")
w('end $$;')
sql = '\n'.join(L) + '\n'

for bad in ('\nbegin;', '\ncommit;', '\nrollback;'):
    assert bad not in sql.lower(), f'the generated SQL carries a transaction statement {bad!r}'

if '--check' in sys.argv:
    ok = os.path.exists(OUT) and open(OUT, encoding='utf-8').read() == sql
    print(f'{NAME}.sql reproduces' if ok else f'{NAME}.sql DIFFERS from what gen_migration.py writes')
    sys.exit(0 if ok else 1)
open(OUT, 'w', encoding='utf-8').write(sql)
print(f'wrote migrations/{NAME}.sql ({len(qs)} question rows, 1 capstone)')
