// W5 RE-CASE GUARD: a re-cased capstone's answers may not be printed before
// the learner works.
//
// FOLLOW-ON-PROGRAMME.md section 3, pick A: the older Ekene and typewell
// capstones graded the case the panels open on and the lessons work, so the
// answer was on screen before the learner did anything. W5 moves each tier to
// a case of its own that the brief states and the learner types into the
// panels. This helper is the gate a course's panelCapstoneGuard.test.js runs,
// in the FC-wave pattern (network, surveillance, relief ...):
//
//   1. THE KEYS ARE THE ENGINE'S. Every graded value is regenerated by the
//      course's keys module, which calls the same teaching functions the
//      panels call, and must equal the committed value exactly.
//   2. NO DEFAULT STATE LANDS ON A GRADED ANSWER (D2). Every course panel is
//      rendered with no props, which is what a learner sees before typing,
//      and every number in it is checked.
//   3. NO LESSON PRINTS ONE. Every lesson of the course, all three tiers.
//   4. NOR DOES ANY PANEL, LAB OR PAGE SOURCE, as a literal.
//   5. NOR DOES THE BRIEF. It states the case's inputs, never an answer.
//
// THE THRESHOLD IS THE GRADER'S OWN, AND IT IS ABSOLUTE:
// `public.academy_submit_capstone` passes a field when abs(got - expected)
// <= tol. A printed number is a leak when typing it would pass: it lies
// within tol of a graded answer. A fraction (unit v/v, frac or fraction) is
// also checked as a percentage, with the band scaled with it, because a
// porosity printed as 21.2 percent is the same answer as 0.212.
//
// WHY NOT THE FC WAVES' TEN TOLERANCES UNDER FIVE UNIT SHIFTS. Those waves
// grade at relative tolerances of 1e-6 to 1e-9, so a band ten times wider is
// still a pinpoint. These older courses grade at percent-level tolerances
// (0.05 MMstb on a 19 MMstb booking, 0.02 on a 0.3 MMstb block): ten of them,
// shifted by x1000 and x100, cover most of the number line and would call
// every depth, count and porosity in the course a leak. The grader's own
// band is the honest line: inside it, a learner who copies the number passes.
//
// A ZERO-TOLERANCE FIELD IS AN INTEGER (a count, a sample). Its band is the
// integer itself, and small integers occur in prose for other reasons, so it
// counts as a leak only where the text around it names what the field counts
// (the field's `context` pattern, within 60 characters; `context_word` is a
// phrase it must match, used by the live-guard control). A zero-tolerance
// field with no context pattern counts on any exact occurrence.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const REPO = path.resolve(HERE, '..', '..', '..', '..');

export const LEAK_GUARD_MARGIN = 1;
const FRACTION_UNITS = new Set(['v/v', 'frac', 'fraction']);
export const isFraction = (f) => FRACTION_UNITS.has(String(f.unit).toLowerCase());
export const NUMBER = /-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?/g;
const WINDOW = 60;

export const OPEN_BOOK = /open book/i;

/** The course's W5 spec (docs/graded-field-audit/w5/<course>.json) with the
 *  new graded fields of its `fields_file` attached to each pick-A tier. A later
 *  wave that re-keys the same fields in place (HD) passes its own fields file. */
export function loadSpec(course, fieldsFile) {
  const p = path.join(REPO, 'docs', 'graded-field-audit', 'w5', `${course}.json`);
  if (!fs.existsSync(p)) throw new Error(`[w5 guard] no spec at ${p}: this gate would check nothing`);
  const spec = JSON.parse(fs.readFileSync(p, 'utf8'));
  if (fieldsFile) spec.fields_file = fieldsFile;
  const fp = path.join(REPO, spec.fields_file);
  if (!fs.existsSync(fp)) throw new Error(`[w5 guard] no fields file at ${fp}: this gate would check nothing`);
  const rows = JSON.parse(fs.readFileSync(fp, 'utf8'));
  Object.entries(spec.tiers).forEach(([tier, t]) => {
    if (t.pick === 'A') t.fields = rows.filter((r) => r.tier === tier);
  });
  return spec;
}

/** Every graded field of the re-cased tiers, as [tier, field]. */
export function gradedFields(spec) {
  const out = [];
  Object.entries(spec.tiers).forEach(([tier, t]) => {
    if (t.pick === 'A') t.fields.forEach((f) => out.push([tier, f]));
  });
  return out;
}

export function leakGuardTargets(spec) {
  const out = [];
  gradedFields(spec).forEach(([tier, f]) => {
    if (f.tol > 0) {
      out.push({ tier, key: f.key, tag: 'as graded', value: f.expected, band: LEAK_GUARD_MARGIN * f.tol });
      if (isFraction(f)) {
        out.push({ tier, key: f.key, tag: 'a fraction restated as a percentage', value: f.expected * 100, band: LEAK_GUARD_MARGIN * f.tol * 100 });
      }
    } else {
      out.push({ tier, key: f.key, tag: 'exact integer', value: f.expected, band: 0,
        context: f.context ? new RegExp(f.context, 'i') : null });
    }
  });
  return out;
}

/** The target a number at `index` in `text` collides with, or null. */
export function leakGuardHit(value, targets, text = null, index = 0) {
  if (!Number.isFinite(value)) return null;
  for (const t of targets) {
    if (t.band > 0) {
      if (Math.abs(value - t.value) <= t.band) return t;
    } else if (value === t.value) {
      if (!t.context || text === null) return t;
      const around = text.slice(Math.max(0, index - WINDOW), index + WINDOW);
      if (t.context.test(around)) return t;
    }
  }
  return null;
}

/** Every leak in a text, as readable strings. */
export function scanText(text, targets, where) {
  const hits = [];
  for (const m of text.matchAll(NUMBER)) {
    const hit = leakGuardHit(Number(m[0]), targets, text, m.index);
    if (hit) {
      const line = text.slice(0, m.index).split('\n').length;
      hits.push(`${where}:${line} prints ${m[0]}, inside ${hit.tier}/${hit.key} (${hit.tag})`);
    }
  }
  return hits;
}

export function courseLessons(course) {
  const root = path.join(REPO, 'src', 'content', 'courses', course);
  const out = [];
  const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.md')) out.push(p);
  });
  walk(root);
  return out;
}

const markupText = (html) => html.replace(/<[^>]+>/g, ' ').replace(/&[a-z]+;/g, ' ');

/** What each panel shows before the learner types: a render with no props. */
export function defaultRenders(panels) {
  return Object.entries(panels).map(([file, mod]) => ({
    file,
    text: markupText(renderToStaticMarkup(React.createElement(mod.default))),
  }));
}

/**
 * The whole gate. `panels` is import.meta.glob('./*Explorer.jsx', { eager: true })
 * from the course's panel directory; `sources` lists every other file a learner
 * can reach (the teaching lib, the learning page), relative to the repo root.
 */
export function defineCaseGuard({ describe, it, expect, spec, compute, panels, course, sources, capstoneLessons }) {
  const fields = gradedFields(spec);
  const targets = leakGuardTargets(spec);
  const aTiers = Object.entries(spec.tiers).filter(([, t]) => t.pick === 'A').map(([k]) => k);

  describe(`${course}: THE KEYS ARE THE ENGINE'S`, () => {
    it('reads the re-cased tiers and their fields from the committed spec', () => {
      expect(spec.course).toBe(course);
      expect(aTiers.length).toBeGreaterThan(0);
      expect(fields.length).toBeGreaterThanOrEqual(aTiers.length * 6);
      aTiers.forEach((tier) => expect(spec.tiers[tier].fields.map((f) => f.tier)).toEqual(spec.tiers[tier].rekey.map(() => tier)));
      fields.forEach(([tier, f]) => {
        expect(Number.isFinite(f.expected), `${tier}.${f.key}`).toBe(true);
        expect(f.tol, `${tier}.${f.key}`).toBeGreaterThanOrEqual(0);
        if (f.tol === 0) expect(Number.isInteger(f.expected), `${tier}.${f.key} is tol 0 and not an integer`).toBe(true);
      });
    });

    it('every committed value is exactly what the engine gives on the stated case', () => {
      const got = compute(spec.tiers);
      fields.forEach(([tier, f]) => {
        expect(got[tier][f.key], `${tier}.${f.key}`).toBe(f.expected);
      });
    });
  });

  describe(`${course}: NO DEFAULT STATE, LESSON, SOURCE OR BRIEF PRINTS A GRADED ANSWER`, () => {
    it('THE GUARD IS LIVE: a planted value inside the band is caught, and one far outside is not', () => {
      fields.forEach(([tier, f]) => {
        if (f.tol > 0) {
          const drift = 0.9 * LEAK_GUARD_MARGIN * f.tol;
          const planted = [f.expected + drift, f.expected - drift, f.expected];
          if (isFraction(f)) planted.push(f.expected * 100);
          planted.forEach((v) => {
            expect(leakGuardHit(v, targets), `${tier}.${f.key} planted at ${v}`).not.toBeNull();
          });
          // just outside the grader's band, the field's own target no longer fires
          [f.expected + 1.1 * LEAK_GUARD_MARGIN * f.tol, f.expected - 1.1 * LEAK_GUARD_MARGIN * f.tol].forEach((v) => {
            const hit = leakGuardHit(v, targets.filter((t) => t.key === f.key && t.tier === tier));
            expect(hit, `${tier}.${f.key} at ${v} is outside its band`).toBeNull();
          });
        } else {
          const planted = `the case has ${f.expected} ${f.context_word || ''}`;
          if (f.context) expect(f.context_word, `${tier}.${f.key} has a context pattern and no context_word`).toBeTruthy();
          expect(scanText(planted, targets, 'planted').length, `${tier}.${f.key} planted as "${planted}"`).toBeGreaterThan(0);
        }
      });
      expect(leakGuardHit(NaN, targets)).toBeNull();
    });

    it('no panel prints a graded answer in its default state (D2)', () => {
      const renders = defaultRenders(panels);
      expect(renders.length).toBeGreaterThanOrEqual(3);
      const hits = renders.flatMap((r) => scanText(r.text, targets, `${r.file} (default render)`));
      expect(hits).toEqual([]);
    });

    it('no lesson of the course prints one, in any tier', () => {
      const files = courseLessons(course);
      expect(files.length).toBeGreaterThan(40);
      const hits = files.flatMap((p) => scanText(fs.readFileSync(p, 'utf8'), targets, path.relative(REPO, p)));
      expect(hits).toEqual([]);
    });

    it('no panel, lab or page source carries one as a literal', () => {
      const dir = path.join(REPO, 'src', 'components', 'course', 'panels', course);
      const files = [
        ...fs.readdirSync(dir).filter((f) => /\.(jsx?|mjs)$/.test(f) && !f.endsWith('.test.js') && !f.endsWith('.test.jsx'))
          .map((f) => path.join(dir, f)),
        ...sources.map((s) => path.join(REPO, s)),
      ];
      files.forEach((p) => expect(fs.existsSync(p), `${p} is missing, so this gate would check nothing`).toBe(true));
      const hits = files.flatMap((p) => scanText(fs.readFileSync(p, 'utf8'), targets, path.relative(REPO, p)));
      expect(hits).toEqual([]);
    });

    it('the brief states the case and never an answer, and carries no open-book label', () => {
      aTiers.forEach((tier) => {
        const t = spec.tiers[tier];
        expect(scanText(t.prompt, targets, `${tier} brief`)).toEqual([]);
        expect(t.prompt, `${tier} brief`).not.toMatch(OPEN_BOOK);
      });
    });

    it('the capstone lesson of each re-cased tier has dropped its open-book note', () => {
      Object.entries(capstoneLessons).forEach(([tier, rel]) => {
        const p = path.join(REPO, 'src', 'content', 'courses', course, rel);
        expect(fs.existsSync(p), p).toBe(true);
        expect(fs.readFileSync(p, 'utf8'), `${tier} capstone lesson`).not.toMatch(OPEN_BOOK);
      });
      expect(Object.keys(capstoneLessons).sort()).toEqual([...aTiers].sort());
    });
  });
}
