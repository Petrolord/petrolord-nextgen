// W5c (section 3 pick A, all tiers), petrophysics: the IKPO-3 capstone well.
//
// Every petrophysics capstone graded the bundled typewell, which every panel
// opens on and every walkthrough worked. The capstones move to IKPO-3, a well
// no panel loads: a 201-sample analytic well built here the way the typewell
// fixture was built (shale-fraction profile with cosine ramps, a compaction
// porosity trend, GR/RHOB/DT/NPHI from defined apparent porosities, RT by
// exact Archie inversion in clean rock and a conductivity blend in shale),
// written as a LAS 2.0 file the learner downloads and opens in the panels.
// The keys are regenerated by parsing that LAS with the vendored parser and
// running the panel lab (typewellLab.js, petrophysicsTeaching.js), which calls
// the vendored petrophysics engines. Nothing here computes a graded value.
// The course constants (TW: matrix and fluid, Archie a m n and Rw, cutoffs,
// GR clean and clay, Rsh) are the typewell's givens, unchanged.
import { parseLas } from '../../../../packages/engines/engines/welldata/lasParse.js';
import {
  TW, wellFromLas, porosityCurves, vshLinearCurve, swCurve, zoneMean, fitPickett, bookSandA, waterLegMeanSw,
  rwArps, rweFromSsp,
} from '../../../../src/components/course/panels/petrophysics/typewellLab.js';
import { computeWorkflow, defaultParams } from '../../../../src/lib/petrophysicsTeaching.js';

export const ZONES = { SAND_A: [1712, 1734], SAND_B: [1752, 1781] };
export const WATER_LEG = [1776, 1779];
export const PICKETT_WINDOW = [1773, 1779];
export const LAB = { rwSample: 0.1128, tSampleF: 72, tFmF: 172, sspMv: -90, rmfe: 0.6 };

// Design knobs, chosen by a search that keeps every precise key clear of the
// numbers the lessons print and the Pickett window fit physically sensible.
export const DESIGN = { phiTop: 0.3, phiGrad: 0.0022, swGas: 0.37, swOilTop: 0.55 };

const TOP = 1700;
const STEP = 0.5;
const N = 201;
const ramp = (z, a, b) => 0.5 - 0.5 * Math.cos(Math.PI * Math.min(1, Math.max(0, (z - a) / (b - a))));

function shale(z) {
  // clean inside each sand, 2 m cosine ramps across each boundary
  const inSand = (top, base) => (z <= top - 1 || z >= base + 1 ? 0
    : Math.min(ramp(z, top - 1, top + 1), 1 - ramp(z, base - 1, base + 1)));
  return 1 - Math.max(inSand(...ZONES.SAND_A), inSand(...ZONES.SAND_B));
}

function swTarget(z) {
  if (z <= ZONES.SAND_A[1] + 1) return DESIGN.swGas; // the gas sand
  if (z >= WATER_LEG[0]) return 1; // the water leg and below
  // SAND_B oil column grading into the water leg
  return Math.min(1, DESIGN.swOilTop + ((1 - DESIGN.swOilTop) * (z - ZONES.SAND_B[0])) / (WATER_LEG[0] - ZONES.SAND_B[0]));
}

const r5 = (v) => Math.round(v * 1e5) / 1e5;

export function buildCurves() {
  const c = { DEPT: [], GR: [], RHOB: [], NPHI: [], DT: [], RT: [] };
  for (let i = 0; i < N; i++) {
    const z = TOP + STEP * i;
    const s = shale(z);
    const gas = z <= ZONES.SAND_A[1] + 1 && s < 1 ? 1 : 0;
    const phi = (DESIGN.phiTop - DESIGN.phiGrad * (z - TOP)) * (1 - s);
    const phiApp = phi + 0.03 * gas * (1 - s);
    const rhob = (1 - s) * (TW.rho_ma - phiApp * (TW.rho_ma - TW.rho_fl)) + s * TW.rho_sh;
    const dt = (1 - s) * (TW.dt_ma + phi * (TW.dt_fl - TW.dt_ma)) + s * 238.88;
    const nphi = phi + 0.3 * s - 0.08 * gas * (1 - s);
    const sw = swTarget(z);
    const rtClean = phi > 0 ? (TW.a * TW.rw) / (phi ** TW.m * sw ** TW.n) : Infinity;
    const rt = 1 / ((1 - s) / rtClean + s / TW.rsh);
    c.DEPT.push(z); c.GR.push(r5(TW.gr_clean + (TW.gr_clay - TW.gr_clean) * s)); c.RHOB.push(r5(rhob));
    c.NPHI.push(r5(nphi)); c.DT.push(r5(dt)); c.RT.push(r5(rt));
  }
  // a few missing samples, away from the graded windows' edges
  c.GR[40] = null; c.RHOB[70] = null; c.NPHI[70] = null; c.DT[110] = null; c.RT[190] = null;
  return c;
}

const f = (v) => (v == null ? '-999.2500' : v.toFixed(5)).padStart(12);

export function lasText(c = buildCurves()) {
  const L = [
    '~Version ---------------------------------------------------',
    'VERS.   2.0 : CWLS LOG ASCII STANDARD - VERSION 2.0',
    'WRAP.   NO  : ONE LINE PER DEPTH STEP',
    '~Well ------------------------------------------------------',
    `STRT.M  ${c.DEPT[0].toFixed(4)} : START DEPTH`,
    `STOP.M  ${c.DEPT[N - 1].toFixed(4)} : STOP DEPTH`,
    `STEP.M  ${STEP.toFixed(4)} : STEP`,
    'NULL.   -999.25 : NULL VALUE',
    'COMP.   PETROLORD : COMPANY',
    'WELL.   IKPO 3 : WELL',
    'FLD .   IKPO : FIELD',
    'LOC .   ONSHORE NIGER DELTA : LOCATION',
    'UWI .   IKPO-3 : UNIQUE WELL ID',
    '~Curve Information -----------------------------------------',
    'DEPT.M     : 1  DEPTH',
    'GR  .GAPI  : 2  GAMMA RAY',
    'RHOB.G/C3  : 3  BULK DENSITY',
    'NPHI.V/V   : 4  NEUTRON POROSITY',
    'DT  .US/M  : 5  SONIC TRANSIT TIME',
    'RT  .OHMM  : 6  TRUE RESISTIVITY',
    '~Other -----------------------------------------------------',
    'Petrolord NextGen capstone case - docs/graded-field-audit/w5c/petrophysics/case.mjs',
    '~ASCII -----------------------------------------------------',
  ];
  for (let i = 0; i < N; i++) {
    L.push([c.DEPT[i].toFixed(4).padStart(10), f(c.GR[i]), f(c.RHOB[i]), f(c.NPHI[i]), f(c.DT[i]), f(c.RT[i])].join(''));
  }
  return L.join('\n') + '\n';
}

// The well the learner's panels build from the downloaded LAS and the zones
// the brief states.
export function caseWell(text = lasText()) {
  return wellFromLas(parseLas(text), { name: 'IKPO-3', zones: ZONES, waterLeg: WATER_LEG });
}

export function gradedKeys(text = lasText()) {
  const well = caseWell(text);
  // Associate: the booking recipe (density porosity, Larionov tertiary Vsh, Archie, the given cutoffs)
  const wf = computeWorkflow(defaultParams(), { curves: well.CURVES, zones: well.ZONES });
  const A = wf.zones.SAND_A;
  const B = wf.zones.SAND_B;
  // Professional: N-D (average) and Wyllie porosity, the Pickett fit in the window, shaly-sand Sw with linear Vsh
  const por = porosityCurves({ rhoMa: TW.rho_ma, rhoFl: TW.rho_fl, dtMa: TW.dt_ma, dtFl: TW.dt_fl, ndMethod: 'avg' }, well);
  const fit = fitPickett(por.phiNdArr, PICKETT_WINDOW[0], PICKETT_WINDOW[1], well);
  const vsh = vshLinearCurve(TW.gr_clean, TW.gr_clay, well);
  const shaly = (method) => swCurve({ method, phi: por.phiNdArr, vsh, rw: TW.rw, rsh: TW.rsh, a: TW.a, m: TW.m, n: TW.n }, well);
  // Expert: Rw triangulation and the two bookings
  const rwA = rwArps(LAB.rwSample, LAB.tSampleF, LAB.tFmF);
  const rwe = rweFromSsp(LAB.sspMv, LAB.rmfe, LAB.tFmF);
  const corrected = bookSandA(rwA, well);
  const raw = bookSandA(LAB.rwSample, well);
  return {
    beginner: [
      { key: 'ikpo3_sand_a_net_m', tol: 0.75, unit: 'm', label: 'IKPO-3 SAND_A net pay', expected: A.net_m },
      { key: 'ikpo3_sand_a_phi_avg', tol: 0.01, unit: 'v/v', label: 'IKPO-3 SAND_A average porosity', expected: A.phi_avg },
      { key: 'ikpo3_sand_a_sw_avg', tol: 0.02, unit: 'v/v', label: 'IKPO-3 SAND_A average Sw', expected: A.sw_avg },
      { key: 'ikpo3_sand_b_net_m', tol: 0.75, unit: 'm', label: 'IKPO-3 SAND_B net pay', expected: B.net_m },
      { key: 'ikpo3_sand_b_phi_avg', tol: 0.01, unit: 'v/v', label: 'IKPO-3 SAND_B average porosity', expected: B.phi_avg },
      { key: 'ikpo3_sand_b_sw_avg', tol: 0.02, unit: 'v/v', label: 'IKPO-3 SAND_B average Sw', expected: B.sw_avg },
    ],
    intermediate: [
      { key: 'ikpo3_phind_avg_sand_a', tol: 0.002, unit: 'v/v', label: 'IKPO-3 SAND_A mean neutron-density porosity', expected: zoneMean(por.phiNdArr, well.ZONES.SAND_A, well) },
      { key: 'ikpo3_phiw_avg_sand_a', tol: 0.002, unit: 'v/v', label: 'IKPO-3 SAND_A mean Wyllie sonic porosity', expected: zoneMean(por.phiW, well.ZONES.SAND_A, well) },
      { key: 'ikpo3_pickett_a_rw', tol: 0.002, unit: 'Ω·m', label: 'IKPO-3 Pickett fit over 1773 to 1779 m: a·Rw', expected: fit.aRw },
      { key: 'ikpo3_pickett_m', tol: 0.0002, unit: '-', label: 'IKPO-3 Pickett fit over 1773 to 1779 m: cementation exponent m', expected: fit.m },
      { key: 'ikpo3_sw_sim_sand_a', tol: 0.01, unit: 'v/v', label: 'IKPO-3 SAND_A mean Sw (Simandoux)', expected: zoneMean(shaly('simandoux'), well.ZONES.SAND_A, well) },
      { key: 'ikpo3_sw_ind_sand_a', tol: 0.01, unit: 'v/v', label: 'IKPO-3 SAND_A mean Sw (Indonesia)', expected: zoneMean(shaly('indonesia'), well.ZONES.SAND_A, well) },
    ],
    advanced: [
      { key: 'ikpo3_rw_arps', tol: 0.00005, unit: 'ohm.m', label: 'IKPO-3 sample Rw at formation temperature (Arps)', expected: rwA },
      { key: 'ikpo3_rwe_ssp', tol: 0.00005, unit: 'ohm.m', label: 'IKPO-3 Rwe from the SP quicklook', expected: rwe },
      { key: 'ikpo3_sw_waterleg_mean', tol: 0.0005, unit: 'v/v', label: 'IKPO-3 water-leg mean Sw with the Arps Rw', expected: waterLegMeanSw(rwA, well) },
      { key: 'ikpo3_sand_a_net_arps', tol: 0.01, unit: 'm', label: 'IKPO-3 SAND_A net pay with the Arps Rw', expected: corrected.net_m },
      { key: 'ikpo3_sand_a_sw_avg_arps', tol: 0.005, unit: 'v/v', label: 'IKPO-3 SAND_A pay-average Sw with the Arps Rw', expected: corrected.sw_avg },
      { key: 'ikpo3_sand_a_net_uncorrected', tol: 0.01, unit: 'm', label: 'IKPO-3 SAND_A net pay with the raw sample Rw', expected: raw.net_m },
    ],
    fit: { nPoints: fit.nPoints, r2: fit.r2 },
  };
}
