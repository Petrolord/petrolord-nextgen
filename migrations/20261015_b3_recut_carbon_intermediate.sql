-- B3 RECUT, INTERMEDIATE TIER: Carbon & Energy Efficiency (carbon)
-- question text brought to petrolord-engines e972ae7 (engines PR #232).
--
-- WHY. Engines #232 recasts engine sentences that broke the owner copy rule
-- (contrastives such as "X, not Y" and "rather than") and gives the queue
-- its facility vocabularies (a CNG forecourt now speaks of dispensers). It
-- moves no value. This LIVE bank quoted the old sentences verbatim, so the
-- quotes are brought to the engine's words. Text only.
--
-- WHAT MOVES. 1 of the 132 questions of this tier, 0 with a changed keyed
-- answer TEXT and 0 with a changed answer INDEX. No ord, no module key, no
-- scope, no option order and no row count moves, so every question id and
-- every learner attempt against it survives.
-- Fields rewritten: 1 explanation.
-- Rows (scope, module_key, ord):
--   module m04-what-tuning-is-worth ord 1: explanation
--
-- GUARDS. Each row is addressed by its stable identity (app_slug, tier, scope,
-- module_key, ord) and must match EITHER its published text exactly, in which
-- case it is updated, OR the recut text exactly, in which case it is already
-- applied and left alone. Anything else raises and the transaction rolls back.
-- Every update asserts it touched exactly 1 row, and the tier must still hold
-- 132 questions at the end.
--
-- The published strings are the rows migrations/20261014_cef_carbon_intermediate_deep.sql wrote
-- (APPLIED 2026-09-19), regenerated byte for byte from the banks before this
-- recut. The recut strings are the recut banks. Written by
-- docs/b3-engine-strings-recut/gen_recut.py; see RECUT-carbon.json.
--
-- SAFE TO RE-RUN. A second run finds every row already carrying the recut
-- text and updates nothing.
-- ==========================================================================

do $$
declare
  v_state   text;
  v_count   integer;
  v_updated integer := 0;
begin

  -- module m04-what-tuning-is-worth ord 1: explanation
  select case
           when prompt = 'SECTION 14 prints the engine''s method for the saving from tuning the invented Isiokpo heater. Which ratio does it give?' and options = '["(target - current) / current", "(target - current) / target", "(target - current) / a hundred", "(target - current) / (target + current)"]'::jsonb and answer_index = 1 and explanation = 'The method, verbatim: "Fuel scales inversely with efficiency at the same duty, so the saving is (target - current) / target. Subtracting the efficiency percentages divides by a hundred instead of by the target efficiency, and understates the saving."' then 'old'
           when prompt = 'SECTION 14 prints the engine''s method for the saving from tuning the invented Isiokpo heater. Which ratio does it give?' and options = '["(target - current) / current", "(target - current) / target", "(target - current) / a hundred", "(target - current) / (target + current)"]'::jsonb and answer_index = 1 and explanation = 'The method, verbatim: "Fuel scales inversely with efficiency at the same duty, so the saving is (target - current) / target. The divisor is the target efficiency. Subtracting the efficiency percentages divides by a hundred and understates the saving."' then 'new'
           else 'other' end
    into v_state
    from public.academy_quiz_questions where app_slug = 'carbon' and tier = 'intermediate' and scope = 'module' and module_key is not distinct from 'm04-what-tuning-is-worth'::text and ord = 1;
  if v_state is null then raise exception 'B3 recut carbon intermediate refused: no row for module m04-what-tuning-is-worth ord 1'; end if;
  if v_state = 'other' then raise exception 'B3 recut carbon intermediate refused: module m04-what-tuning-is-worth ord 1 matches neither its published nor its recut text'; end if;
  if v_state = 'old' then
    update public.academy_quiz_questions
       set prompt = 'SECTION 14 prints the engine''s method for the saving from tuning the invented Isiokpo heater. Which ratio does it give?', options = '["(target - current) / current", "(target - current) / target", "(target - current) / a hundred", "(target - current) / (target + current)"]'::jsonb, answer_index = 1, explanation = 'The method, verbatim: "Fuel scales inversely with efficiency at the same duty, so the saving is (target - current) / target. The divisor is the target efficiency. Subtracting the efficiency percentages divides by a hundred and understates the saving."'
     where app_slug = 'carbon' and tier = 'intermediate' and scope = 'module' and module_key is not distinct from 'm04-what-tuning-is-worth'::text and ord = 1;
    get diagnostics v_count = row_count;
    if v_count <> 1 then raise exception 'B3 recut carbon intermediate refused: module m04-what-tuning-is-worth ord 1 updated % rows', v_count; end if;
    v_updated := v_updated + 1;
  end if;

  select count(*) into v_count from public.academy_quiz_questions where app_slug = 'carbon' and tier = 'intermediate';
  if v_count <> 132 then raise exception 'B3 recut carbon intermediate refused: carbon intermediate holds % questions, expected 132', v_count; end if;
  raise notice 'B3 recut carbon intermediate: % of 1 rows updated, % already recut', v_updated, 1 - v_updated;
end
$$;
