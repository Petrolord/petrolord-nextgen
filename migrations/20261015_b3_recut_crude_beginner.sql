do $$
declare
  v_state   text;
  v_count   integer;
  v_updated integer := 0;
begin

  -- final final ord 31: options, explanation KEYED ANSWER TEXT CHANGED
  select case
           when prompt = 'When the gravity rule does not flag the export blend, what does the engine''s message say about the result?' and options = '["That the blend screens stable on gravity contrast, pending a SARA analysis.", "That the blend is uncertain and needs a spot test to ASTM D7112 or D7157.", "That the spread is not the classic combination, which is no evidence the blend is stable.", "That no stability screen was made because not every crude has a gravity."]'::jsonb and answer_index = 2 and explanation = 'The message reads, in part: The gravity spread is not the classic heavy-plus-light-paraffinic combination, which is not evidence that the blend is stable. Supply SARA for a real index.' then 'old'
           when prompt = 'When the gravity rule does not flag the export blend, what does the engine''s message say about the result?' and options = '["That the blend screens stable on gravity contrast, pending a SARA analysis.", "That the blend is uncertain and needs a spot test to ASTM D7112 or D7157.", "That the spread falls outside the classic combination, and that alone says nothing of stability.", "That no stability screen was made because not every crude has a gravity."]'::jsonb and answer_index = 2 and explanation = 'The message reads, in part: The gravity spread falls outside the classic heavy-plus-light-paraffinic combination, and that alone says nothing about whether the blend is stable. Supply SARA for a real index.' then 'new'
           else 'other' end
    into v_state
    from public.academy_quiz_questions where app_slug = 'crude' and tier = 'beginner' and scope = 'final' and module_key is not distinct from null::text and ord = 31;
  if v_state is null then raise exception 'B3 recut crude beginner refused: no row for final final ord 31'; end if;
  if v_state = 'other' then raise exception 'B3 recut crude beginner refused: final final ord 31 matches neither its published nor its recut text'; end if;
  if v_state = 'old' then
    update public.academy_quiz_questions
       set prompt = 'When the gravity rule does not flag the export blend, what does the engine''s message say about the result?', options = '["That the blend screens stable on gravity contrast, pending a SARA analysis.", "That the blend is uncertain and needs a spot test to ASTM D7112 or D7157.", "That the spread falls outside the classic combination, and that alone says nothing of stability.", "That no stability screen was made because not every crude has a gravity."]'::jsonb, answer_index = 2, explanation = 'The message reads, in part: The gravity spread falls outside the classic heavy-plus-light-paraffinic combination, and that alone says nothing about whether the blend is stable. Supply SARA for a real index.'
     where app_slug = 'crude' and tier = 'beginner' and scope = 'final' and module_key is not distinct from null::text and ord = 31;
    get diagnostics v_count = row_count;
    if v_count <> 1 then raise exception 'B3 recut crude beginner refused: final final ord 31 updated % rows', v_count; end if;
    v_updated := v_updated + 1;
  end if;

  select count(*) into v_count from public.academy_quiz_questions where app_slug = 'crude' and tier = 'beginner';
  if v_count <> 132 then raise exception 'B3 recut crude beginner refused: crude beginner holds % questions, expected 132', v_count; end if;
  raise notice 'B3 recut crude beginner: % of 1 rows updated, % already recut', v_updated, 1 - v_updated;
end
$$;
