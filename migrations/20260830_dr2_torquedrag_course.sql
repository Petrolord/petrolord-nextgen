-- The ONLY thing that changes between them is the shape of the hole, which is
-- the whole subject. casingwear_cases.json adds the horizontal well's
-- rotate-on-bottom side forces against 1200 m of casing.
--
-- THE CAPSTONE RUNS AT A DIFFERENT MUD WEIGHT FROM THE LESSONS. 1500 kg/m3
-- rather than 1440, and a two-entry rotating schedule (30 h at 150 rpm then
-- 20 h at 90 rpm) rather than the single 50 h at 120 rpm the lessons teach on.
-- The first version of this field set graded the same conditions the lessons
-- used, and the tier-leakage sweep found ten downward leaks and thirty-eight
-- same-tier answer prints. Changing the capstone's conditions rather than
-- stripping the numbers out of the lessons keeps the teaching intact and makes
-- every graded value one the learner has to produce. The sweep over all 78
-- lessons and all 21 banks now reports 0 and 0.
--
-- THE SCOPE DECISION THAT SHAPES THIS COURSE. engines/drilling implements a
-- SOFT-STRING model. It has no stiff-string analysis, no dynamics (stick-slip,
-- whirl, axial oscillation, static versus kinetic friction), no hydraulic or
-- thermal effects on the string (piston forces, ballooning, thermal length
-- change), and no post-lock-up behaviour: it flags buckling and does NOT
-- change the friction, so its answers past the helical limit are optimistic.
-- Expert m05 l05 teaches all four with their mechanisms and their value
-- stated, and grades none. 20260830_dr2_torquedrag_go_live.sql asserts it.
--
-- THE CASE THAT SETTLES A DISAGREEMENT BETWEEN TWO IMPLEMENTATIONS. The
-- goldens were generated by an independent RK4 integration of the same ODE.
-- Over 100+ published summaries and checkpoints the two agree to better than
-- 1e-4 relative EXCEPT on two operations of the horizontal well, both of which
-- put the string in compression along a lateral: worst relative 6.70e-2 and
-- worst absolute 1632.220696788194 N. Halving the step halves the horizontal
-- gap (1196.69 N at 10 m to 45.94 N at 0.25 m) and does NOT move the slant
-- one, which settles at -32.650164601625875 N. So one is discretisation and
-- the other is a model difference. The vertical well settles which
-- implementation is closer: it has a closed form, the buoyed weight of the
-- string at 732311.468284047 N, which the engine reproduces to about 4e-9 N
-- and the oracle misses by 42.6224374640733 N. That result is TAUGHT, across
-- Professional m05 and Expert m05 l04, and is graded nowhere.
--
-- A RESULT THE TEST FOUND. The helical buckling limit is exactly
-- 2*sqrt(2) - 1 times the sinusoidal one, to 1e-9, at every inclination, in
-- every hole size and for every pipe, because both come from the same
-- expression with a different constant in front. torquedragLab.test.js
-- asserts it, and Expert m01 l05 teaches it as a one-second check on any
-- implementation, with the caveat that published derivations use different
-- helical coefficients so the constant is fixed within an implementation and
-- not across them.
--
-- Oracle values reproduced from the vendored engine in Node BEFORE this
-- migration was written (DR2-TRUTH.md, dr2_fields.mjs); torquedragLab.test.js
-- pins all eighteen through the course's own teaching lab, so a panel and the
-- live grader cannot drift apart. Pairwise tolerance-collision check across
-- all eighteen: 0 fatal, 0 notes, re-asserted inside the test at each field's
-- OWN tolerance rather than a flat one, because the buoyancy factor and a
-- friction factor are 0.42 apart and a flat 0.5 would have failed a set that
-- is fine.
