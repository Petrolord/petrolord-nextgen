  if (select (md5(prompt) = '01dc40f61d05dca5c727dd2b1428ec67' and md5(dataset) = 'b10adcd4b8a4c91cd2bf7924de43d475' and fields = '[{"key": "oduma2_n_samples", "tol": 0, "unit": "count", "label": "oduma2_main: depth samples", "expected": 437}, {"key": "oduma2_gr_nulls", "tol": 0, "unit": "count", "label": "oduma2_main: GR null samples", "expected": 13}, {"key": "oduma2_gr_mean", "tol": 0.05, "unit": "GAPI", "label": "oduma2_main: mean GR (finite samples)", "expected": 76.99698143635156}, {"key": "oduma3_step_m", "tol": 0.001, "unit": "m", "label": "oduma3_feet: depth step, converted", "expected": 0.0762}, {"key": "oduma5_pef_nulls", "tol": 0, "unit": "count", "label": "oduma5_nulls: PEF null samples", "expected": 241}, {"key": "oduma1_n_samples", "tol": 0, "unit": "count", "label": "oduma1_wrapped: depth samples", "expected": 207}]'::jsonb) from public.academy_capstones where app_slug = 'welldata' and tier = 'beginner' and active) is not true then
