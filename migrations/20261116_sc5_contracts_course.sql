    (slug, name, module, path_order, status, prereq_slug, course_type, review_date, sources_checked_on)
values ('contracts', 'Contract & Supplier Management', 'supply_chain', 79, 'coming_soon', null,
        'practice', date '2027-09-27', date '2026-09-27')
on conflict (slug) do nothing;

do $$
begin
  if not exists (select 1 from public.academy_apps
                  where slug = 'contracts' and course_type = 'practice'
                    and review_date = date '2027-09-27'
                    and sources_checked_on = date '2026-09-27') then
    raise exception 'contracts: the catalogue row is not the practice row this migration writes';
  end if;
  if exists (select 1 from public.academy_capstones where app_slug = 'contracts') then
    raise exception 'contracts: a practice course carries no capstone row';
  end if;
end $$;
