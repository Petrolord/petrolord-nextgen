begin

  -- module m05-the-schedule ord 15: explanation
  select case
           when prompt = 'Which three things does the engine''s note on ABUA''s schedule name as not modelled?' and options = '["Cargo sizes, unit runs and lifts.", "Crude costs, product prices and unit operating costs.", "Time zones, the clock change and the period start.", "Tank capacity, jetty windows and turnarounds."]'::jsonb and answer_index = 3 and explanation = 'The note reads "Tank capacity, jetty windows and turnarounds are not modelled: this is the shape of the month to read actuals against, not a berth-level schedule." A turnaround is entered in the plan, as a unit typed as shut.' then 'old'
