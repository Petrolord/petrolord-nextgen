  if v_state = 'old' then
    update public.academy_quiz_questions
       set prompt = 'What does the engine''s basis sentence say of unburned ethane and heavier?', options = '["They are counted as methane, one molecule a carbon atom.", "They carry no GWP here; only the methane does.", "They carry the methane GWP.", "They pass through the flare as the CO2 in the gas does."]'::jsonb, answer_index = 1, explanation = 'The basis sentence closes: "Unburned ethane and heavier carry no GWP here." Only the methane in the gas enters the CH4 half of the rule.'
     where app_slug = 'gasvalue' and tier = 'beginner' and scope = 'module' and module_key is not distinct from 'm04-the-flare-by-the-rule'::text and ord = 4;
