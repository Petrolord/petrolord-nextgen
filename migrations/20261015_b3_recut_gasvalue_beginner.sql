    if v_count <> 1 then raise exception 'B3 recut gasvalue beginner refused: module m04-the-flare-by-the-rule ord 4 updated % rows', v_count; end if;
    v_updated := v_updated + 1;
  end if;

  select count(*) into v_count from public.academy_quiz_questions where app_slug = 'gasvalue' and tier = 'beginner';
  if v_count <> 132 then raise exception 'B3 recut gasvalue beginner refused: gasvalue beginner holds % questions, expected 132', v_count; end if;
