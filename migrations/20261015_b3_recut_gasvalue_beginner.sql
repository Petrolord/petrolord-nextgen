do $$
declare
  v_state   text;
  v_count   integer;
  v_updated integer := 0;
begin

  -- module m04-the-flare-by-the-rule ord 4: options, explanation KEYED ANSWER TEXT CHANGED
  select case
           when prompt = 'What does the engine''s basis sentence say of unburned ethane and heavier?' and options = '["They are counted as methane, one molecule a carbon atom.", "They are not methane and carry no GWP here.", "They carry the methane GWP.", "They pass through the flare as the CO2 in the gas does."]'::jsonb and answer_index = 1 and explanation = 'The basis sentence closes: "Unburned ethane and heavier are not methane and carry no GWP here." Only the methane in the gas enters the CH4 half of the rule.' then 'old'
